/// A project's languages counted as GitHub counts a repository's (§2.6),
/// after its Linguist: each language's bytes, of the files that are
/// programming or markup (not data, not prose), less what's vendored
/// (kept from elsewhere), documentation, or generated — by Linguist's
/// own path patterns (vendor.yml, documentation.yml), its generated
/// files' names and first lines, and minified scripts — and as the
/// project's `.gitattributes` say otherwise (`linguist-vendored`,
/// `linguist-generated`, `linguist-documentation`,
/// `linguist-detectable`, `linguist-language`).
public enum Linguist {
    public struct Count: Codable, Equatable, Sendable {
        public var name: String
        public var bytes: Int64
        public init(name: String, bytes: Int64) {
            self.name = name
            self.bytes = bytes
        }
    }

    /// The counts for a project's files (relative to its root, with their
    /// sizes), most first. `head` reads a file's beginning, for what's
    /// generated or minified; `attributes`, its `.gitattributes` files.
    public static func count(_ files: [(path: String, size: Int64)], attributes: Attributes = Attributes(),
                             head: (String) -> String? = { _ in nil }) -> [Count] {
        var bytes: [String: Int64] = [:]
        for (path, size) in files {
            let name: String
            if let given = attributes.value("linguist-language", for: path), given != "false", given != "true" {
                name = given
            } else if let l = CodeLanguage.forPath(path) {
                // Programming and markup, unless it says it's to be counted.
                guard l.countsAsCode || attributes.bool("linguist-detectable", for: path) == true else { continue }
                name = l.name
            } else {
                continue
            }
            if attributes.bool("linguist-detectable", for: path) == false { continue }
            if attributes.bool("linguist-vendored", for: path) ?? isVendored(path) { continue }
            if attributes.bool("linguist-documentation", for: path) ?? isDocumentation(path) { continue }
            if attributes.bool("linguist-generated", for: path) ?? isGenerated(path, head: { head(path) }) { continue }
            bytes[name, default: 0] += size
        }
        return bytes.map { Count(name: $0.key, bytes: $0.value) }.sorted { $0.bytes != $1.bytes ? $0.bytes > $1.bytes : $0.name < $1.name }
    }

    // MARK: What's set aside

    public static func isVendored(_ path: String) -> Bool { vendored.matches(path) }
    public static func isDocumentation(_ path: String) -> Bool { documentation.matches(path) }

    /// Generated: by its name (protocol buffers' and Thrift's output, lock
    /// files, source maps, Xcode's…), else by what its first lines say
    /// ("Code generated … DO NOT EDIT", "@generated", "Generated by"), or,
    /// a script or a style sheet, by being minified (lines 110 characters
    /// long on average).
    public static func isGenerated(_ path: String, head: () -> String?) -> Bool {
        if generatedNames.matches(path) { return true }
        let ext = path.pathExtension.lowercased()
        guard CodeLanguage.forPath(path) != nil, let text = head() else { return false }
        let lines = text.split(separator: "\n", maxSplits: 6, omittingEmptySubsequences: false).prefix(6)
        for line in lines where generatedMarks.matches(String(line)) { return true }
        if ["js", "mjs", "cjs", "css"].contains(ext) {
            let all = text.split(separator: "\n", omittingEmptySubsequences: false)
            if !all.isEmpty, text.count / all.count > 110 { return true }
        }
        return false
    }

