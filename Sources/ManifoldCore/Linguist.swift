    /// A list of regular expressions, any of which matching is a match.
    struct Patterns: @unchecked Sendable {
        let regexes: [NSRegularExpression]
        init(_ patterns: [String]) { regexes = patterns.compactMap { try? NSRegularExpression(pattern: $0) } }
        func matches(_ s: String) -> Bool {
            let r = NSRange(s.startIndex..., in: s)
            return regexes.contains { $0.firstMatch(in: s, range: r) != nil }
        }
    }

    // MARK: .gitattributes

    /// A project's `.gitattributes` files, each by the folder it's in
    /// (relative to the root, "" for the root's): what they set, the
    /// deeper file's and the later line's saying over the rest's, as git
    /// reads them.
    public struct Attributes: Sendable {
        struct Rule: @unchecked Sendable {
            var regex: NSRegularExpression
            var values: [String: String]
        }
        var rules: [Rule] = []

        public init() {}

        /// From the files' texts, by the folder each is in.
        public init(_ files: [(folder: String, text: String)]) {
            for (folder, text) in files.sorted(by: { $0.folder.split(separator: "/").count < $1.folder.split(separator: "/").count }) {
                for raw in text.split(separator: "\n") {
                    let line = raw.trimmingCharacters(in: .whitespaces)
                    guard !line.isEmpty, !line.hasPrefix("#") else { continue }
                    let words = line.split(whereSeparator: \.isWhitespace).map(String.init)
                    guard let pattern = words.first, let regex = Self.regex(pattern, in: folder) else { continue }
                    var values: [String: String] = [:]
                    for w in words.dropFirst() {
                        if w.hasPrefix("-") { values[String(w.dropFirst())] = "false" }
                        else if w.hasPrefix("!") { values[String(w.dropFirst())] = "unset" }
                        else if let eq = w.firstIndex(of: "=") { values[String(w[..<eq])] = String(w[w.index(after: eq)...]) }
                        else { values[w] = "true" }
                    }
                    if values.keys.contains(where: { $0.hasPrefix("linguist-") }) { rules.append(Rule(regex: regex, values: values)) }
                }
            }
        }

        /// An attribute's value for a path: the last rule's that matches and says it.
        public func value(_ attribute: String, for path: String) -> String? {
            let r = NSRange(path.startIndex..., in: path)
            for rule in rules.reversed() {
                guard let v = rule.values[attribute], rule.regex.firstMatch(in: path, range: r) != nil else { continue }
                return v == "unset" ? nil : v
            }
            return nil
        }

        public func bool(_ attribute: String, for path: String) -> Bool? {
            switch value(attribute, for: path)?.lowercased() {
            case "true", "1": true
            case "false", "0": false
            default: nil
            }
        }

        /// A gitattributes pattern as a regular expression over paths
        /// relative to the root: one without a slash matches a name at any
        /// depth under its folder; one with a slash, from its folder; `*`
        /// within a name, `**` across folders, `?` a character. As git
        /// has it, a folder's pattern (`docs/`) matches nothing, and a
        /// name not what's in the folder it names: `docs/**` does.
        static func regex(_ pattern: String, in folder: String) -> NSRegularExpression? {
            var p = pattern
            guard !p.hasSuffix("/") else { return nil }
            let anchored = p.contains("/")
            if p.hasPrefix("/") { p.removeFirst() }
            var out = ""
            var i = p.startIndex
            while i < p.endIndex {
                let c = p[i]
                let next = p.index(after: i)
                if c == "*", next < p.endIndex, p[next] == "*" {
                    let after = p.index(after: next)
                    if after < p.endIndex, p[after] == "/" {
                        out += "(.*/)?"
                        i = p.index(after: after)
                    } else {
                        out += ".*"
                        i = after
                    }
                    continue
                }
                switch c {
                case "*": out += "[^/]*"
                case "?": out += "[^/]"
                case "[": out += "["
                case "]": out += "]"
                default: out += NSRegularExpression.escapedPattern(for: String(c))
                }
                i = next
            }
            let base = folder.isEmpty ? "" : NSRegularExpression.escapedPattern(for: folder) + "/"
            let start = anchored ? "^" + base : "^" + base + "(.*/)?"
            // A folder's pattern holds what's under it too.
            return try? NSRegularExpression(pattern: start + out + "$")
        }
    }
}

extension CodeLanguage {
    /// Counted among a project's languages, as Linguist counts them: a
    /// programming language or markup (HTML, CSS, TeX), build scripts
    /// (Make, CMake, Dockerfile, Just) among them; not data
    /// (configuration, lock files) or patches.
    public var countsAsCode: Bool {
        switch kind {
        case .language: true
        case .build: id != "gradle"
        case .markup: id != "diff"
        case .data: false
        }
    }
}
